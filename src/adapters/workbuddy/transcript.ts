// WorkBuddy owns this on-disk format: <workbuddyHome>/projects/<proj>/<sessionId>.jsonl (excluding subagents/).
// Hub verifies delivery candidates and MCP send_message posts after reading the bound session.
import { lstat } from 'node:fs/promises';
import { emptyTranscriptPage, truncateTranscriptText, type TranscriptItem, type TranscriptPage, type TranscriptRequest, type TranscriptSource } from '../../core/types.ts';
import { inspectTranscriptPrefix, readTranscriptPage, type TranscriptDraft } from '../shared/transcript.ts';
import { SESSION_RE } from './store.ts';

const QUIET_TYPES = new Set(['session-meta', 'file-history-snapshot', 'ai-title', 'credit-usage']);
const SHELL_WAIT_TOOLS = new Set(['Bash', 'PowerShell', 'Shell']);

type JsonObject = Record<string, unknown>;
const obj = (value: unknown): JsonObject | undefined =>
  value !== null && typeof value === 'object' && !Array.isArray(value) ? value as JsonObject : undefined;
const str = (value: unknown): string | undefined => typeof value === 'string' ? value : undefined;
const label = (value: unknown): string | undefined =>
  typeof value === 'string' && value.length > 0 && value.length <= 256 ? value : undefined;
const escapeRegex = (value: string) => value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

function isoTime(value: unknown): string | undefined {
  if (typeof value === 'number' && Number.isFinite(value) && value > 0) {
    const d = new Date(value);
    return Number.isNaN(d.getTime()) ? undefined : d.toISOString();
  }
  if (typeof value === 'string' && value.length <= 40 && Number.isFinite(Date.parse(value))) {
    return new Date(value).toISOString();
  }
  return undefined;
}

function messageText(content: unknown, fallbackLabel: string): string | undefined {
  if (typeof content === 'string') return content;
  if (!Array.isArray(content)) return undefined;
  const parts: string[] = [];
  for (const item of content) {
    if (typeof item === 'string') {
      parts.push(item);
      continue;
    }
    const block = obj(item);
    if ((block?.type === 'input_text' || block?.type === 'output_text' || block?.type === 'text') && typeof block.text === 'string') {
      parts.push(block.text);
    }
  }
  if (parts.length) return parts.join('\n');
  return content.length ? fallbackLabel : '';
}

function toolOutput(output: unknown): string | undefined {
  if (typeof output === 'string') return output;
  const block = obj(output);
  if (block?.type === 'text' && typeof block.text === 'string') return block.text;
  if (Array.isArray(output)) {
    const parts: string[] = [];
    for (const item of output) {
      const b = obj(item);
      if (b?.type === 'text' && typeof b.text === 'string') parts.push(b.text);
    }
    if (parts.length) return parts.join('\n');
    return output.length ? '[Non-text tool output]' : undefined;
  }
  if (output !== undefined && output !== null) return '[Non-text tool output]';
  return undefined;
}

function postId(output: string): string | undefined {
  if (!output || output.length > 64 * 1024) return undefined;
  for (const candidate of [output, output.split(/\r?\n/, 1)[0]!]) {
    try {
      const value = obj(JSON.parse(candidate));
      if (value && Array.isArray(value.deliveredTo) && value.deliveredTo.every((n) => typeof n === 'string')) {
        return label(value.messageId);
      }
    } catch { /* regular tool output */ }
  }
  return undefined;
}

const WAIT_TICKET_RE = /\b[a-z]1\.[A-Za-z0-9._-]{1,128}\.[0-9a-f]{64}\b/g;
const redactWaitTickets = (text: string) => text.replace(WAIT_TICKET_RE, '[redacted]');

function waitCommandRegex(sessionId: string): RegExp {
  // Exact full command generated by waitCommand(WORKBUDDY_WAIT, ...):
  //   node "<script>/wait.mjs" w1.<sessionId>.<64hex> http://127.0.0.1:<port> workbuddy [WorkBuddy.exe]
  const scriptPath = `(?:"[^"$\`%!\\\\\\r\\n]*wait\\.mjs"|[^\\s"'$\`%!;&|<>()\\r\\n]*wait\\.mjs)`;
  return new RegExp(
    `^node(?:\\.exe)?\\s+${scriptPath}\\s+w1\\.${escapeRegex(sessionId)}\\.[0-9a-f]{64}\\s+http:\\/\\/127\\.0\\.0\\.1:\\d{1,5}\\s+workbuddy(?:\\s+WorkBuddy\\.exe)?$`,
  );
}

function stripStderrAndBlankTail(lines: string[]): string | undefined {
  const stderrIdx = lines.findIndex((ln) => /^Stderr(?:\s*\([^)]*\))?:\s*(?:\(empty\))?$/.test(ln));
  const sliced = stderrIdx >= 0 ? lines.slice(0, stderrIdx) : lines.slice();
  while (sliced.at(-1) === '') sliced.pop();
  const body = sliced.join('\n');
  if (!body || body === '(empty)') return undefined;
  return body;
}

function extractTaskOutputWait(output: string, waitCmdRe: RegExp, timestamp?: string): NonNullable<TranscriptSource['candidate']> | undefined {
  const lines = output.replace(/\r\n/g, '\n').split('\n');
  const stdoutIdx = lines.findIndex((ln) => /^Stdout(?:\s*\([^)]*\))?:\s*$/.test(ln));
  if (stdoutIdx <= 0) return undefined;
  const headerLines = lines.slice(0, stdoutIdx);
  const cmdLine = headerLines.find((ln) => ln.startsWith('Command:'));
  const cmd = cmdLine?.slice('Command:'.length).trim();
  if (!cmd || !waitCmdRe.test(cmd)) return undefined;
  const body = stripStderrAndBlankTail(lines.slice(stdoutIdx + 1));
  if (!body) return undefined;
  if (body.startsWith('[orrery] cluster=')) return { envelope: body.split('\n', 1)[0]! };
  return { direct: { body, ...(timestamp ? { at: timestamp } : {}) } };
}

function extractShellStdout(output: string): string | undefined {
  const lines = output.replace(/\r\n/g, '\n').split('\n');
  const start = /^Stdout(?:\s*\([^)]*\))?:\s*$/.test(lines[0] ?? '') ? 1 : 0;
  return stripStderrAndBlankTail(lines.slice(start));
}

function commandMatchesWait(callArgsText: string | undefined, waitCmdRe: RegExp): boolean {
  if (!callArgsText) return false;
  try {
    const parsed = obj(JSON.parse(callArgsText));
    const cmd = str(parsed?.command) ?? str(parsed?.cmd) ?? str(parsed?.script);
    return !!cmd && waitCmdRe.test(cmd.trim());
  } catch {
    return false;
  }
}

type MetaState = 'match' | 'empty' | 'conflict' | 'unsupported';

function inspectSessionMeta(prefix: Buffer, sessionId: string): MetaState {
  if (prefix.length === 0) return 'empty';
  const firstEnd = prefix.indexOf(10);
  if (firstEnd < 0 && prefix.length >= 64 * 1024) return 'unsupported';
  const firstLine = (firstEnd < 0 ? prefix.toString('utf8') : prefix.toString('utf8', 0, firstEnd)).replace(/\r$/, '');
  if (!firstLine.trim()) return firstEnd < 0 ? 'empty' : 'unsupported';
  try {
    const row = obj(JSON.parse(firstLine));
    if (!row || row.type !== 'session-meta') return 'unsupported';
    return row.sessionId === sessionId ? 'match' : 'conflict';
  } catch {
    return 'unsupported';
  }
}

function parse(
  value: unknown,
  waitCmdRe: RegExp,
  shellCallArgs: Map<string, string>,
  shellOutputs?: Map<string, string>,
): TranscriptDraft[] | undefined {
  const row = obj(value);
  if (!row) return undefined;
  const type = label(row.type);
  const timestamp = isoTime(row.timestamp);
  if (type && QUIET_TYPES.has(type)) return [];

  const unknown = (name?: string): TranscriptDraft => ({
    kind: 'unknown',
    name,
    text: '[Unrecognized WorkBuddy record]',
    timestamp,
  });

  switch (row.type) {
    case 'message': {
      const id = label(row.id) ? `wb:msg:${label(row.id)}` : undefined;
      if (row.role === 'user') {
        const text = messageText(row.content, '[Non-text user content]');
        if (text === undefined) return [unknown('user')];
        const isMeta = obj(row.providerData)?.isMeta === true;
        return [{
          ...(id ? { id } : {}),
          kind: isMeta ? 'system' : 'user',
          ...(isMeta ? { name: 'meta' } : {}),
          ...truncateTranscriptText(text),
          timestamp,
        }];
      }
      if (row.role === 'assistant') {
        const text = messageText(row.content, '[Non-text assistant content]');
        if (text === undefined) return [unknown('assistant')];
        return [{
          ...(id ? { id } : {}),
          kind: 'assistant',
          ...truncateTranscriptText(text),
          timestamp,
        }];
      }
      return [unknown(label(row.role) ?? 'message')];
    }

    case 'reasoning': {
      const id = label(row.id) ? `wb:reason:${label(row.id)}` : undefined;
      // Never expose rawContent or raw reasoning text.
      return [{ ...(id ? { id } : {}), kind: 'thinking', timestamp }];
    }

    case 'function_call': {
      const rawName = label(row.name);
      const callId = label(row.callId);
      const rowId = label(row.id);
      const argsRaw = typeof row.arguments === 'string' ? row.arguments
        : row.arguments !== undefined ? JSON.stringify(row.arguments) : undefined;
      let displayName = rawName;
      let toolName = rawName;
      let toolServer: string | undefined;

      if (rawName === 'DeferExecuteTool' && argsRaw) {
        try {
          const parsed = obj(JSON.parse(argsRaw));
          const inner = label(parsed?.toolName);
          if (inner) {
            displayName = inner;
            const mcp = /^mcp__(.+?)__(.+)$/.exec(inner);
            if (mcp) {
              toolServer = mcp[1];
              toolName = mcp[2];
            } else {
              toolName = inner;
            }
          }
        } catch { /* keep DeferExecuteTool name */ }
      } else if (rawName) {
        const mcp = /^mcp__(.+?)__(.+)$/.exec(rawName);
        if (mcp) {
          toolServer = mcp[1];
          toolName = mcp[2];
        }
      }

      if (callId && rawName && SHELL_WAIT_TOOLS.has(rawName) && argsRaw !== undefined) {
        shellCallArgs.set(callId, argsRaw);
      }

      return [{
        ...(callId ? { id: `wb:call:${callId}`, callId } : rowId ? { id: `wb:fn:${rowId}` } : {}),
        kind: 'tool_call',
        name: displayName,
        timestamp,
        ...(argsRaw === undefined ? {} : truncateTranscriptText(redactWaitTickets(argsRaw))),
        ...(callId ? { source: { toolCallId: callId, ...(toolName ? { toolName } : {}), ...(toolServer ? { toolServer } : {}) } } : {}),
      }];
    }

    case 'function_call_result': {
      const rawName = label(row.name);
      const callId = label(row.callId);
      const rowId = label(row.id);
      const pd = obj(row.providerData);
      const tr = obj(pd?.toolResult);
      const isError = (row.status !== undefined && row.status !== 'completed')
        || pd?.isError === true || tr?.isError === true || tr?.error !== undefined;
      const outputText = toolOutput(row.output);

      let postMessageId: string | undefined;
      let candidate: NonNullable<TranscriptSource['candidate']> | undefined;

      if (!isError && callId && (rawName === 'DeferExecuteTool' || rawName?.startsWith('mcp__')) && outputText !== undefined) {
        // Never set source.candidate on MCP/DeferExecuteTool results: a miss would suppress orrery_post checks.
        postMessageId = postId(outputText);
      } else if (!isError && rawName === 'TaskOutput' && outputText) {
        candidate = extractTaskOutputWait(outputText, waitCmdRe, timestamp);
      } else if (!isError && callId && rawName && SHELL_WAIT_TOOLS.has(rawName) && outputText && shellOutputs) {
        // Defer candidate attachment until the paired tool_call is verified against the full wait command.
        shellOutputs.set(callId, outputText);
      }

      const hasSource = Boolean(callId || candidate);
      return [{
        ...(callId ? { id: `wb:res:${callId}`, callId } : rowId ? { id: `wb:fnres:${rowId}` } : {}),
        kind: 'tool_result',
        name: rawName,
        timestamp,
        ...(outputText === undefined ? {} : truncateTranscriptText(redactWaitTickets(outputText))),
        ...(hasSource ? {
          source: {
            ...(callId ? { toolCallId: callId } : {}),
            ...(postMessageId ? { postMessageId } : {}),
            ...(candidate ? { candidate } : {}),
          },
        } : {}),
      }];
    }

    default:
      return [unknown(type)];
  }
}

/** Read a bound WorkBuddy session's `<sessionId>.jsonl`, checking `session-meta.sessionId` and excluding subagents. */
export async function readWorkbuddyTranscript(
  projectsDir: string,
  listCandidates: () => Promise<string[]>,
  sessionId: string,
  request: TranscriptRequest,
): Promise<TranscriptPage> {
  if (!SESSION_RE.test(sessionId) || sessionId === '.' || sessionId === '..') return emptyTranscriptPage('refused');
  const candidates = await listCandidates();
  if (!candidates.length) return emptyTranscriptPage('missing');

  const matched: { file: string; mtimeNs: bigint }[] = [];
  const emptyFiles: { file: string; mtimeNs: bigint }[] = [];
  let sawRefused = false;
  let sawUnsupported = false;

  for (const file of candidates) {
    const st = await lstat(file, { bigint: true }).catch((e: NodeJS.ErrnoException) =>
      e.code === 'ENOENT' || e.code === 'ENOTDIR' ? null : ('err' as const));
    if (st === null) continue;
    if (st === 'err' || !st.isFile() || st.nlink !== 1n) {
      sawRefused = true;
      continue;
    }
    const meta = await inspectTranscriptPrefix(projectsDir, file, (prefix) => inspectSessionMeta(prefix, sessionId));
    if (meta === undefined || meta === 'conflict') {
      sawRefused = true;
      continue;
    }
    if (meta === 'unsupported') {
      sawUnsupported = true;
      continue;
    }
    if (meta === 'empty') {
      emptyFiles.push({ file, mtimeNs: st.mtimeNs });
    } else {
      matched.push({ file, mtimeNs: st.mtimeNs });
    }
  }

  let selected: { file: string; mtimeNs: bigint } | undefined;
  if (matched.length) {
    matched.sort((a, b) => (b.mtimeNs > a.mtimeNs ? 1 : b.mtimeNs < a.mtimeNs ? -1 : 0));
    selected = matched[0];
  } else if (sawRefused) {
    return emptyTranscriptPage('refused');
  } else if (emptyFiles.length && !sawUnsupported) {
    emptyFiles.sort((a, b) => (b.mtimeNs > a.mtimeNs ? 1 : b.mtimeNs < a.mtimeNs ? -1 : 0));
    selected = emptyFiles[0];
  } else if (sawUnsupported) {
    return emptyTranscriptPage('unsupported');
  } else {
    return emptyTranscriptPage('missing');
  }

  const waitCmdRe = waitCommandRegex(sessionId);
  const shellCallArgs = new Map<string, string>();
  const shellOutputs = new Map<string, string>();

  const read = (req: TranscriptRequest, recordShells: boolean) => readTranscriptPage({
    root: projectsDir,
    file: selected.file,
    sessionKey: sessionId,
    request: req,
    prepare(prefix) {
      const meta = inspectSessionMeta(prefix, sessionId);
      if (meta === 'conflict') return 'refused';
      if (meta === 'unsupported') return 'unsupported';
      return undefined;
    },
    parse: (value) => parse(value, waitCmdRe, shellCallArgs, recordShells ? shellOutputs : undefined),
    unknownText: '[Unreadable WorkBuddy record]',
  });

  const page = await read(request, true);
  if (page.status !== 'ok') return page;

  const calls = new Map<string, TranscriptItem>();
  const remember = (item: TranscriptItem) => {
    if (item.kind === 'tool_call' && item.callId) calls.set(item.callId, item);
  };
  const needsLookback = page.items.some((item) => {
    remember(item);
    if (!item.callId || calls.has(item.callId)) return false;
    if (item.source?.postMessageId) return true;
    return item.kind === 'tool_result' && shellOutputs.has(item.callId);
  });
  calls.clear();
  if (needsLookback && page.before) {
    const earlier = await read({ cursor: page.before, direction: 'before', limit: 64 }, false);
    if (earlier.status === 'reset') return emptyTranscriptPage('reset');
    if (earlier.status === 'ok') earlier.items.forEach(remember);
  }

  for (const item of page.items) {
    remember(item);
    if (item.source?.postMessageId) {
      const call = item.callId ? calls.get(item.callId) : undefined;
      const cs = call?.source;
      if (cs?.toolServer && cs.toolName === 'send_message') {
        item.source.toolName = cs.toolName;
        item.source.toolServer = cs.toolServer;
      } else {
        delete item.source.postMessageId;
      }
      continue;
    }
    if (item.kind === 'tool_result' && item.callId && shellOutputs.has(item.callId)) {
      const call = calls.get(item.callId);
      if (call?.name && SHELL_WAIT_TOOLS.has(call.name) && commandMatchesWait(shellCallArgs.get(item.callId), waitCmdRe)) {
        const stdout = extractShellStdout(shellOutputs.get(item.callId)!);
        if (stdout) {
          item.source ??= { toolCallId: item.callId };
          item.source.candidate = stdout.startsWith('[orrery] cluster=')
            ? { envelope: stdout.split('\n', 1)[0]! }
            : { direct: { body: stdout, ...(item.timestamp ? { at: item.timestamp } : {}) } };
        }
      }
    }
  }
  return page;
}
